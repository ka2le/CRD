// Run against Vite dev for deterministic preparation scenarios.
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
const { chromium } = createRequire(import.meta.url)(process.env.CRD_PLAYWRIGHT_MODULE || 'playwright')
const output = resolve(process.env.CRD_BROWSER_OUTPUT || 'artifacts/ui/monsters')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  page.setDefaultTimeout(12000)
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.CRD_URL || 'http://127.0.0.1:5173/')
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('crd-local-game-v1')).state)
  const menu = () => page.getByRole('button', { name: 'Open menu', exact: true }).click()
  const collection = async () => { await menu(); await page.getByRole('button', { name: 'Collection', exact: true }).click() }
  const close = () => page.getByRole('button', { name: 'Close', exact: true }).click()
  const scenario = async () => {
    await page.evaluate(() => window.crdDev.prepare('monsters', { rules: 'monsters' }))
    await page.waitForFunction(() => { const s = JSON.parse(localStorage.getItem('crd-local-game-v1')).state; return s.game.devScenario === 'monsters' && !s.battleStarted && s.preBattle.playerActivated.length === 0 })
  }
  const clickCard = async id => {
    const state = await read()
    const card = state.preBattle.playerHand.find(card => card.id === id)
    await page.locator(`[data-card-uid="${card.uid}"]`).click()
  }
  await menu()
  await page.locator('.screen-menu__toggle').filter({ hasText: 'Testing' }).click()
  await page.getByRole('radio', { name: 'Monsters', exact: true }).click()
  let state = await read()
  assert.equal(state.settings.tabletop, 'monsters')
  assert.equal(state.game.handSize, 6)
  assert.equal(state.game.draftRow.length, 6)
  await page.locator('.shuffle-intro').waitFor({ state: 'hidden' })
  await page.screenshot({ path: `${output}/draft-desktop.png` })
  await collection()
  await page.getByRole('button', { name: 'Edit deck counts', exact: true }).click()
  await page.getByLabel('Monster copies', { exact: true }).fill('8')
  await page.getByLabel('Include Swarm', { exact: true }).uncheck()
  await page.getByRole('button', { name: 'Apply & deal', exact: true }).click()
  state = await read()
  assert.equal(state.settings.monsterDeck.monster1, 8)
  assert.equal(state.settings.monsterDeck.swarm, 0)
  await page.locator('.sheet__body').evaluate(el => { el.scrollTop = 0 })
  await page.screenshot({ path: `${output}/editor-desktop.png` })
  await page.locator('.monster-editor__recipe summary').click()
  const recipe = JSON.parse(await page.getByLabel('Monsters deck recipe').inputValue())
  assert.equal(recipe.total, 88)
  assert.equal(recipe.handSize, 6)
  assert.equal(recipe.packSize, 6)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download recipe' }).click()
  const download = await downloadPromise
  await download.saveAs(`${output}/${recipe.recipeId}.json`)
  const empty = { ...recipe, monsterDeck: Object.fromEntries(Object.keys(recipe.monsterDeck).map(id => [id, 0])) }
  await page.locator('input[type=file]').setInputFiles({ name: 'empty.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(empty)) })
  assert.equal(await page.getByRole('button', { name: 'Apply & deal', exact: true }).isDisabled(), true)
  assert.match(await page.locator('.monster-editor [role=alert]').innerText(), /at least 36/)
  await page.reload()
  state = await read()
  assert.equal(state.settings.monsterDeck.monster1, 8)
  assert.equal(state.settings.monsterDeck.swarm, 0)
  assert.equal(state.game.handSize, 6)
  // Exercise an entire six-pack draft through real browser input.
  for (let pick = 0; pick < 6; pick++) {
    await page.waitForFunction(() => {
      const s = JSON.parse(localStorage.getItem('crd-local-game-v1')).state
      return s.game.phase === 'draft-player-pick' && !s.pendingPlayerDraftPickAnimation
    })
    await page.locator('.pack-area .card[aria-disabled="false"]').first().click()
    await page.waitForFunction(n => JSON.parse(localStorage.getItem('crd-local-game-v1')).state.game.playerHand.length === n, pick + 1)
  }
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('crd-local-game-v1')).state.game.phase === 'battle-ready')
  state = await read()
  assert.equal(state.game.playerHand.length, 6)
  assert.equal(state.game.opponentHand.length, 6)
  assert.equal(state.game.packNumber, 6)
  const allCards = [...state.game.playerHand, ...state.game.opponentHand, ...state.game.deck, ...state.game.draftDiscard]
  assert.equal(allCards.length, 88)
  assert.equal(new Set(allCards.map(c => c.uid)).size, 88)
  assert.equal(allCards.filter(c => c.id === 'swarm').length, 0)
  assert.equal(allCards.filter(c => c.id === 'monster1').length, 8)
  console.log('Recipe persistence and six-pack draft passed')
  await menu()
  await page.getByRole('radio', { name: 'Discard', exact: true }).click()
  state = await read()
  assert.equal(state.game.playerHand.length, 6)
  assert.equal(state.game.opponentHand.length, 6)
  await scenario()
  await clickCard('monster_transform')
  await page.getByRole('button', { name: 'Robots', exact: true }).click()
  state = await read()
  assert.equal(state.preBattle.playerHand.flatMap(c => c.stats).filter(s => s === 'monster').length, 0)
  assert.equal(state.preBattle.playerHand.flatMap(c => c.stats).filter(s => s === 'robot').length, 2)
  await page.reload()
  state = await read()
  assert.equal(state.preBattle.playerHand.flatMap(c => c.stats).filter(s => s === 'robot').length, 2)
  await scenario()
  await clickCard('monster_draw_discard')
  state = await read()
  assert.equal(state.preBattle.playerPendingDiscard.remaining, 2)
  assert.equal(state.preBattle.playerHand.length, 8)
  await clickCard('monster_draw_discard')
  await clickCard('monster_attack')
  await page.getByRole('button', { name: 'Accept 2/2', exact: true }).click()
  state = await read()
  assert.equal(state.preBattle.playerPendingDiscard, null)
  assert.equal(state.preBattle.playerHand.length, 6)
  console.log('Transformation and Monster draw/discard passed')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.crdDev.result('monsters', { rules: 'monsters' }))
  await page.getByRole('button', { name: 'Skip to result', exact: true }).click()
  await page.getByRole('button', { name: 'View the table', exact: true }).click()
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${output}/battle-mobile.png` })
  assert.equal(await page.locator('.ttr-cell--monster').count(), 2)
  assert(!/NaN/.test(await page.locator('.ttr').innerText()))
  await collection()
  // The editor remains open in component state until the page reloads.
  if (await page.getByRole('button', { name: 'Edit deck counts', exact: true }).count()) await page.getByRole('button', { name: 'Edit deck counts', exact: true }).click()
  await page.screenshot({ path: `${output}/editor-mobile.png` })
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  assert.equal(overflow, false)
  await page.getByRole('tab', { name: 'Specials', exact: true }).click()
  await page.screenshot({ path: `${output}/specials-mobile.png` })
  await close()
  assert.deepEqual(errors, [])
  await writeFile(`${output}/browser-check.json`, JSON.stringify({ passed: true, recipe, errors,
    checks: ['six-pack browser draft', 'six-card Discard', 'exact recipe export/import and reload', 'minimum 36 guard',
      'transformation picker and persistence', 'mandatory Monster draw/discard', 'four-faction battle ledger', 'mobile layout'] }, null, 2))
  console.log('Monsters browser smoke passed: six-card modes, deck recipe, new specials, reload, mobile ledger and assets.')
} finally { await browser.close() }
