import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const { chromium } = createRequire(import.meta.url)(process.env.CRD_PLAYWRIGHT_MODULE || 'playwright')
const output = resolve(process.env.CRD_BROWSER_OUTPUT || 'artifacts/ui/boss-options')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1360, height: 900 } })
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(process.env.CRD_URL || 'http://127.0.0.1:5187/')
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('crd-boss-run-v1')))
  const button = name => page.getByRole('button', { name, exact: true })
  const main = () => page.locator('.boss-dock > button')
  const readyHand = async seat => {
    const types = page.locator(`[data-seat="${seat}"] .boss-factions button`)
    if (await types.count()) await types.first().click()
    else await page.locator(`[data-seat="${seat}"] .boss-player-name`).click()
    assert.equal(await main().textContent(), 'Ready')
    await main().click()
  }
  const options = async () => { await button('Open menu').click(); await button('Boss options').click() }
  const shot = async name => { await page.waitForTimeout(450); await page.screenshot({ path: `${output}/${name}.png` }) }
  const phase = expected => page.waitForFunction(e => JSON.parse(localStorage.getItem('crd-boss-run-v1'))?.phase === e, expected)
  const pick = async which => {
    const s = await read()
    const row = s.options.draftMode === 'separate' ? `[data-draft-seat="${which ?? s.turns[0]}"]` : '[data-draft-seat="shared"]'
    await page.locator(`${row} [data-card-uid]`).first().click()
  }
  const finishDraft = async (stopBeforePrep = false) => {
    for (let n = 0; n < 60; n++) {
      const s = await read()
      if (s.phase === 'prepare') return
      if (stopBeforePrep && s.phase === 'collected' && s.pack === s.options.rounds) return
      if (s.phase === 'draft') await pick(s.turns.at(-1))
      else await main().click()
    }
    throw Error('Draft did not finish')
  }
  const layout = async () => {
    await page.waitForTimeout(450)
    const bad = await page.locator('.boss-header, .boss-dock, .boss-heroes, .boss-enemy, .boss-draft-packs, .boss-options-sheet').evaluateAll(nodes => nodes.flatMap(n => {
      const r = n.getBoundingClientRect()
      return r.width && (r.left < -1 || r.right > innerWidth + 1 || r.bottom > innerHeight + 1) ? [n.className] : []
    }))
    assert.deepEqual(bad, [])
    const cards = await page.locator('.boss-shell .card').evaluateAll(nodes => nodes.flatMap(n => {
      const r = n.getBoundingClientRect()
      const parent = n.closest('.boss-draft-pack, .boss-hero')?.getBoundingClientRect()
      return r.height && (Math.abs(r.width / r.height - 635 / 888) > .003 || parent && (r.left < parent.left - 2 || r.right > parent.right + 2 || r.top < parent.top - 2 || r.bottom > parent.bottom + 2)) ? [n.getAttribute('data-card-uid')] : []
    }))
    assert.deepEqual(cards, [])
    assert.equal(await page.locator('img').evaluateAll(imgs => imgs.filter(i => !i.complete || !i.naturalWidth).length), 0)
  }

  await button('Open menu').click()
  await page.locator('.screen-menu__toggle').filter({ hasText: 'Testing' }).click()
  await button('Boss battle · Co-op').click()
  await phase('setup')
  let s = await read()
  assert.equal(s.options.draftMode, 'separate')
  assert.equal(s.options.absorption, 'all')
  assert.equal(s.options.weakerBonus, false)
  await options()
  await shot('options-desktop')
  for (const v of [{ width: 390, height: 844 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(v)
    await layout()
    await shot(`options-${v.width}`)
    await button('Apply rules & restart deal').scrollIntoViewIfNeeded()
  }
  await page.setViewportSize({ width: 1360, height: 900 })
  await button('Close').click()
  await main().click()
  await phase('draft')
  const original = await read()
  assert.deepEqual(original.rows.map(r => r.length), [4, 4])
  const firstPick = original.rows[0][0]
  // Both packs are live. Player 2 can go first despite the saved pending list.
  for (const i of [0, 1]) assert.equal(await page.locator(`[data-draft-seat="${i}"] [data-card-uid]`).first().getAttribute('aria-disabled'), 'false')
  await pick(1)
  assert.deepEqual((await read()).hands.map(h => h.length), [0, 1])
  assert.equal(await main().count(), 0)
  assert.equal(await page.locator('[data-draft-seat="1"] [data-card-uid]').first().getAttribute('aria-disabled'), 'true')
  await page.locator('[data-draft-seat="1"] [data-card-uid]').first().click({ force: true })
  assert.deepEqual((await read()).hands.map(h => h.length), [0, 1])
  await page.reload(); await phase('draft')
  await pick(0); await phase('collect')
  assert.equal(await button('Player 2 2 now').isEnabled(), true)
  await button('Player 2 2 now').click()
  await pick(1); await phase('collect')
  assert.deepEqual((await read()).hands.map(h => h.length), [1, 2])
  await button('Player 1 Pocket').click()
  await page.locator('.boss-pocket-preview .card').click()
  await page.locator(`[data-seat="0"] [data-card-uid="${firstPick.uid}"]`).click()
  await main().click()
  assert.equal((await read()).rows[0].some(c => c.uid === firstPick.uid), true)
  assert.equal((await read()).hands[0][0].uid, (await read()).pockets[0].uid)
  await button('Open menu').click(); await button('Restart same deal').click()
  for (const seat of [1, 0]) {
    await button(`Player ${seat + 1} Refresh`).click()
    const other = page.locator(`[data-draft-seat="${1 - seat}"] [data-card-uid]`).first()
    assert.equal(await other.getAttribute('aria-disabled'), 'true')
    await other.click({ force: true })
    assert.equal(await main().isDisabled(), true)
    await page.locator(`[data-draft-seat="${seat}"] [data-card-uid]`).first().click()
    await main().click()
    assert.equal((await read()).playerTools[seat].refresh, 0)
    if (seat === 1) assert.equal((await read()).playerTools[0].refresh, 1)
  }
  await page.reload(); await phase('draft')
  assert.deepEqual((await read()).playerTools.map(t => t.refresh), [0, 0])
  await button('Open menu').click(); await button('Restart same deal').click()
  for (const v of [{ width: 1360, height: 900 }, { width: 390, height: 844 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(v)
    await layout()
    await shot(`separate-draft-${v.width}`)
  }
  await page.setViewportSize({ width: 1360, height: 900 })
  await pick()
  assert.equal((await read()).hands[0][0].uid, firstPick.uid)
  await page.reload()
  await phase('draft')
  assert.equal((await read()).hands[0][0].uid, firstPick.uid)
  await options()
  await page.getByLabel('Test mode', { exact: false }).check()
  await button('Close').click()
  assert.doesNotMatch(await page.locator('.boss-dock').innerText(), /Test mode|Undo|Jump|Both players pick|Round/)
  assert.equal(await button('View').count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Pick a card', exact: true }).count(), 0)
  for (const seat of [0, 1]) assert.equal(await page.locator(`[data-seat="${seat}"] .boss-player-powers button`).count(), 4)
  for (const v of [{ width: 390, height: 844 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(v)
    await layout()
    await shot(`test-draft-${v.width}`)
  }
  await page.setViewportSize({ width: 1360, height: 900 })
  const beforePick = await read()
  await pick()
  await options(); await button('Undo last action').click()
  assert.deepEqual((await read()).hands, beforePick.hands)
  await options(); await button('Fill picks & jump to prep').click()
  await phase('prepare')
  const beforePrep = await read()
  assert.deepEqual(beforePrep.hands.map(h => h.length), [5, 5])
  assert.equal(beforePrep.absorbed.length, 30)
  assert.equal(beforePrep.prep.playerHand[0].uid, firstPick.uid)
  await shot('prepare-desktop')
  for (const v of [{ width: 390, height: 844 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(v)
    await layout()
    await shot(`prepare-${v.width}`)
  }
  await page.setViewportSize({ width: 1360, height: 900 })
  await readyHand(1)
  assert.equal((await read()).prep.opponentFinished, true)
  assert.equal((await read()).prep.playerFinished, false)
  await readyHand(0)
  await phase('result')
  s = await read()
  assert.equal(s.result.weakerBonus, 0)
  assert.equal(s.result.teamPower, s.result.heroes[0].score + s.result.heroes[1].score)
  assert.equal(await page.locator('.boss-result__bonus').count(), 0)
  await shot('result-desktop')
  await page.locator('.boss-result-actions').getByRole('button', { name: 'Replay prep', exact: true }).click()
  assert.deepEqual((await read()).prep, beforePrep.prep)
  await options()
  await button('Back to draft start').click()
  await phase('draft')
  assert.deepEqual((await read()).rows, original.rows)
  // Player 2's tools can also go first and repay only Player 2's next-round pick.
  await button('Player 2 2 now').click()
  await button('Player 2 Pocket').click()
  await page.locator('.boss-pocket-preview .card').click()
  assert.deepEqual((await read()).hands.map(h => h.length), [0, 1])
  assert.equal(await button('Player 1 2 now').isEnabled(), true)
  await button('Player 1 2 now').click()
  await button('Player 1 Pocket').click()
  await page.locator('.boss-pocket-preview .card').click()
  await pick(0)
  await phase('draft')
  await pick(1)
  await phase('collect')
  await main().click(); await main().click()
  assert.deepEqual((await read()).turns, [])
  await phase('collect')
  assert.deepEqual((await read()).hands.map(h => h.length), [2, 2])
  assert.deepEqual((await read()).playerTools.map(t => t.double), [0, 0])
  await main().click(); await main().click()
  await phase('draft')
  await button('Open menu').click()
  await button('Restart same deal').click()
  assert.deepEqual((await read()).rows, original.rows)
  assert.deepEqual((await read()).hands, [[], []])
  // Swap remains live after final absorption, until the actual Prepare press.
  await finishDraft(true)
  await phase('collected')
  assert.equal(await main().textContent(), 'Prepare')
  for (const seat of [1, 2]) assert.equal(await button(`Player ${seat} Swap`).isEnabled(), true)
  await page.reload(); await phase('collected')
  const beforeSwap = await read()
  const a = beforeSwap.hands[0][0], b = beforeSwap.hands[1][0]
  await button('Player 1 Swap').click()
  await page.locator(`[data-seat="0"] [data-card-uid="${a.uid}"]`).click()
  await page.locator(`[data-seat="1"] [data-card-uid="${b.uid}"]`).click()
  await main().click()
  assert.equal((await read()).phase, 'collected')
  assert.equal((await read()).hands[0][0].uid, b.uid)
  assert.equal((await read()).hands[1][0].uid, a.uid)
  assert.equal(await button('Player 1 Swap').isDisabled(), true)
  assert.equal(await button('Player 2 Swap').isEnabled(), true)
  await page.reload(); await phase('collected')
  assert.equal(await button('Player 2 Swap').isEnabled(), true)
  const afterFirstSwap = await read()
  const a2 = afterFirstSwap.hands[0][1], b2 = afterFirstSwap.hands[1][1]
  await button('Player 2 Swap').click()
  await page.locator(`[data-seat="0"] [data-card-uid="${a2.uid}"]`).click()
  await page.locator(`[data-seat="1"] [data-card-uid="${b2.uid}"]`).click()
  await main().click()
  assert.deepEqual((await read()).playerTools.map(t => t.swap), [0, 0])
  assert.equal((await read()).hands[0][1].uid, b2.uid)
  assert.equal((await read()).hands[1][1].uid, a2.uid)
  await shot('final-swap-before-prepare')
  await main().click(); await phase('prepare')
  assert.equal((await read()).prep.playerHand[0].uid, b.uid)
  assert.equal((await read()).prep.opponentHand[0].uid, a.uid)
  for (const seat of [1, 2]) assert.equal(await button(`Player ${seat} Swap`).isDisabled(), true)
  await options()
  await button('Original shared draft').click()
  await button('Apply rules & restart deal').click()
  await phase('setup')
  s = await read()
  assert.equal(s.seed, original.seed)
  assert.equal(s.options.weakerBonus, true)
  await main().click()
  assert.equal((await read()).row.length, 5)
  await finishDraft()
  await readyHand(0); await readyHand(1)
  await phase('result')
  s = await read()
  assert.equal(s.result.weakerBonus, Math.min(...s.result.heroes.map(h => h.score)))
  // Four-round version, all tools off, and independent scoring toggle.
  await options()
  await button('Separate 4-card packs').click()
  await page.getByLabel('Draft rounds', { exact: true }).selectOption('4')
  for (const label of ['Pocket cards', 'Refresh', 'Swap', '2 now · borrow next pick']) await page.getByLabel(label, { exact: true }).uncheck()
  await button('Apply rules & restart deal').click()
  await main().click()
  assert.equal(await page.locator('.boss-tools').getByRole('button', { name: 'Pocket', exact: true }).count(), 0)
  await finishDraft()
  assert.deepEqual((await read()).hands.map(h => h.length), [4, 4])
  await page.reload(); await phase('prepare')
  assert.equal((await read()).testMode, true)
  await button('Open menu').click(); await page.locator('.screen-menu__popover').getByRole('button', { name: 'Replay prep', exact: true }).click()
  await phase('prepare')
  await options(); await page.locator('.boss-options').getByRole('button', { name: 'Choose boss', exact: true }).click()
  await page.locator('.sheet [data-card-uid="boss_ironhide"]').click()
  await phase('setup')
  const beforeFresh = await read()
  await options(); await button('Fresh deal').click()
  assert.notEqual((await read()).seed, beforeFresh.seed)
  assert.equal((await read()).bossId, 'ironhide')
  assert.equal((await read()).options.rounds, 4)
  await button('Open menu').click(); await button('Normal play').click()
  assert.equal(await page.locator('.boss-shell').count(), 0)
  assert.deepEqual(errors, [])
  await writeFile(`${output}/verification.json`, JSON.stringify({ pass: true, errors, checks: ['separate four-card packs', 'either player picks first', 'finished pack locks', 'collection waits for both players', 'either player uses Pocket and borrowed pick first', 'late Pocket and borrowed pick after both picks', 'Swap after final absorption/reload', 'swapped hands enter preparation', 'spent Swap charges stay spent in prep', 'own-pack enforcement', 'all leftovers', 'additive team power', 'desktop/portrait/landscape draft and menu', 'fixed card proportions', 'reload', 'undo', 'jump keeps real picks', 'prep replay', 'draft replay', 'same-seed restart', 'original preset', 'four-round variant', 'disabled tools', 'boss selection', 'fresh deal', 'normal-play exit'] }, null, 2))
  console.log(`Boss options browser checks passed: ${output}`)
} finally { await browser.close() }
